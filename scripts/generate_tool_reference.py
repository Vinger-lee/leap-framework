"""Generate the MCP reference from profiles.py and the tool implementations."""
from __future__ import annotations

import argparse
import ast
import copy
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from leap.runtime.notes import obsidian_note
from leap.runtime.profiles import ALL_TOOL_NAMES, QUICKSTART_TOOL_NAMES
from leap.tools import LeapService


def registered_tools():
    implementations = implementation_tools()
    return [implementations[name] for name in ALL_TOOL_NAMES]


def implementation_tools():
    return {method.name: method
            for path in sorted((ROOT / "src/leap/tools").glob("*.py"))
            for cls in ast.parse(path.read_text(encoding="utf-8")).body
            if isinstance(cls, ast.ClassDef)
            for method in cls.body if isinstance(method, ast.FunctionDef)}


def render():
    tools = registered_tools()
    lines = ["# MCP tool reference", "", "Generated by `python scripts/generate_tool_reference.py`; do not edit by hand.",
             "", f"{len(tools)} registered tools. Order comes from `src/leap/runtime/profiles.py`; "
             "parameters and descriptions come directly from `src/leap/tools/`.", "",
             f"`full` exposes all {len(tools)} tools; `quickstart` exposes {len(QUICKSTART_TOOL_NAMES)}. "
             "Each entry lists the profiles that expose it.", ""]
    for tool in tools:
        args = copy.deepcopy(tool.args)
        args.args = args.args[1:]  # Service methods bind self before registration.
        signature = getattr(getattr(LeapService, tool.name), "__mcp_signature__", None)
        parameters = str(signature).split(" -> ")[0][1:-1] if signature is not None else ast.unparse(args)
        profiles = "full, quickstart" if tool.name in QUICKSTART_TOOL_NAMES else "full"
        lines += [f"## `{tool.name}`", "", f"Profiles: {profiles}.", "",
                  f"```python\n{tool.name}({parameters})\n```", "",
                  ast.get_docstring(tool) or "", ""]
    return obsidian_note("\n".join(lines), title="MCP tool reference", topic="LEAP MCP stdio registered tool signatures",
                         tags=["leap", "reference"], links=["Knowledge_Index", "docs/teaching-delivery", "docs/INTEGRATION", "docs/INTEGRATION_CN"]).rstrip()+"\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "docs/mcp-tools.md"
    content = render()
    if args.check:
        return int(not target.exists() or target.read_text(encoding="utf-8") != content)
    target.write_bytes(content.encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
