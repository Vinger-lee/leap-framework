"""Generate the public MCP reference from the registered functions in server.py."""
from __future__ import annotations

import argparse
import ast
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from leap.runtime.notes import obsidian_note


def registered_tools():
    tree = ast.parse((ROOT / "src/leap/server.py").read_text(encoding="utf-8"))
    return [n for n in ast.walk(tree) if isinstance(n, ast.FunctionDef)
            and any(isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute)
                    and isinstance(d.func.value, ast.Name) and d.func.value.id == "server"
                    and d.func.attr == "tool" for d in n.decorator_list)]


def render():
    tools = registered_tools()
    lines = ["# MCP tool reference", "", "Generated by `python scripts/generate_tool_reference.py`; do not edit by hand.",
             "", f"{len(tools)} registered tools. Parameters come directly from `src/leap/server.py`.", ""]
    for tool in tools:
        lines += [f"## `{tool.name}`", "", f"```python\n{tool.name}({ast.unparse(tool.args)})\n```", "",
                  ast.get_docstring(tool) or "", ""]
    return obsidian_note("\n".join(lines), title="MCP tool reference", topic="LEAP MCP stdio registered tool signatures",
                         tags=["leap", "reference"], links=["Knowledge_Index", "docs/teaching-delivery", "docs/INTEGRATION", "docs/INTEGRATION_CN"]).rstrip()+"\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "docs/mcp-tools.md"
    content = render()
    if args.check:
        return int(not target.exists() or target.read_text(encoding="utf-8") != content)
    target.write_bytes(content.encode("utf-8"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
